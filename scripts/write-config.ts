// deno run -A scripts/write-config.ts  : .env -> js/config.js (public URL + anon key only)
import { load } from "@std/dotenv";
const env = await load({ envPath: ".env" });
if (!env.SUPABASE_URL || !env.SUPABASE_ANON_KEY) throw new Error("SUPABASE_URL / SUPABASE_ANON_KEY missing in .env");
await Deno.writeTextFile(
  "js/config.js",
  `// Public by design (RLS protects data). Generated by scripts/write-config.ts. Never put the service_role key here.\nexport const SUPABASE_URL = ${JSON.stringify(env.SUPABASE_URL)};\nexport const SUPABASE_ANON_KEY = ${JSON.stringify(env.SUPABASE_ANON_KEY)};\n`,
);
console.log("wrote js/config.js");
